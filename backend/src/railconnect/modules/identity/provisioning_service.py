from sqlalchemy.orm import Session

from railconnect.modules.identity.models.role import Role
from railconnect.modules.identity.models.user import User
from railconnect.modules.identity.models.user_role import UserRole
from railconnect.modules.identity.permissions import RoleCode
from railconnect.modules.identity.provisioning_repository import (
    get_role_by_code,
    get_user_by_username,
    lock_provisioning,
)
from railconnect.modules.identity.provisioning_schemas import ProvisionStaffInput

ROLE_NAMES = {
    RoleCode.CONTROLLER: "Controller",
    RoleCode.ADMINISTRATOR: "Administrator",
}


def provision_staff_user(
    session: Session,
    data: ProvisionStaffInput,
    encoded_password: str,
) -> User:
    if not session.in_transaction():
        raise ValueError("Staff provisioning requires a caller-owned transaction.")

    if not encoded_password.startswith("$argon2id$") or len(encoded_password) > 512:
        raise ValueError("Supply an Argon2id hash generated by the password utility.")

    lock_provisioning(session)

    if get_user_by_username(session, data.username) is not None:
        raise ValueError("That username already exists. No account was changed.")

    role = get_role_by_code(session, data.role.value)

    if role is None:
        role = Role(
            code=data.role.value,
            display_name=ROLE_NAMES[data.role],
        )
        session.add(role)
        session.flush()

    user = User(
        username=data.username,
        display_name=data.display_name,
        password_hash=encoded_password,
        is_active=True,
        auth_version=1,
    )
    session.add(user)
    session.flush()

    session.add(UserRole(user_id=user.id, role_id=role.id))
    session.flush()

    return user
